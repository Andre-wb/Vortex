//! Периодическая очистка внутреннего состояния.
//!
//! Реализуют хранилище блокировок (удаление просроченных) и ограничитель
//! частоты (удаление истории неактивных адресов). Фоновая задача обходит их
//! единообразно, ничего не зная о внутреннем устройстве.

pub trait Prunable: Send + Sync {
    /// Имя для журнала.
    fn name(&self) -> &'static str;

    /// Число удалённых записей.
    fn prune(&self) -> usize;
}
