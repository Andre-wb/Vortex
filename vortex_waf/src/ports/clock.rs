//! Источник текущего времени.
//!
//! DIP: движок, ограничитель частоты и капча зависят от этого трейта, а не от
//! системных часов, поэтому истечение блокировок и окон проверяется в тестах
//! без ожидания.

use crate::domain::timestamp::Timestamp;

pub trait Clock: Send + Sync {
    fn now(&self) -> Timestamp;
}
