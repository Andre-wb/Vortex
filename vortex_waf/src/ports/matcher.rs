//! Предикат поиска совпадения в тексте.
//!
//! Отделён от правила: правило знает *что* значит совпадение, матчер — *как*
//! его найти. Новый способ поиска (подстрока, набор строк, Aho-Corasick)
//! добавляется отдельной реализацией и не трогает остальной код.

pub trait Matcher: Send + Sync {
    fn is_match(&self, input: &str) -> bool;
}
